const assert = require('node:assert/strict');
const fs = require('node:fs');
assert.ok(fs.existsSync(__dirname + '/../pricing.js'), 'pricing module must exist');
const p = require('../pricing.js');
const a = require('../attribution.js');
const expected = {weekday:{esports:[180,490,870,800,540],comfort:[200,540,960,800,600]},weekend:{esports:[200,540,960,800,600],comfort:[220,600,1060,800,660]}};
let cases = 0;
for(const day of Object.keys(expected)) for(const hall of Object.keys(expected[day])) ['hour','three','six','night','morning'].forEach((duration,i)=>{assert.equal(p.quote(day,hall,duration).price,expected[day][hall][i]); cases++;});
assert.equal(p.quote('weekday','ps5','hour'),null);
assert.equal(p.quote('bad','esports','hour'),null);
