assert.deepEqual(a.resolve('',{at:now,params:{password:'secret',utm_source:'vk'}},now).params,{utm_source:'vk'});
assert.equal(a.resolve('?utm_source='+ 'x'.repeat(500),null,now).params.utm_source.length,300);
const b=new URL(a.bookingURL('https://langame.ru/example/booking',old.params,'B'));
assert.equal(b.searchParams.get('arena_variant'),'B');assert.equal(b.searchParams.get('yclid'),'old');
